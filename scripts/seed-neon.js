async function seed() {
  console.log("🌱 Seeding 9 courses to NeonDB...");
  for (const c of courses) {
    const upserted = await prisma.course.upsert({
      where: { slug: c.slug },
      update: {
        title: c.title,
        subtitle: c.subtitle,
        description: c.description,
        longDesc: c.longDesc,
        priceUsdt: c.priceUsdt,
        image: c.image,
        category: c.category,
        tags: c.tags,
        instructor: c.instructor,
        duration: c.duration,
        lessons: c.lessons,
        level: c.level,
        featured: c.featured,
        rating: c.rating,
        reviewCount: c.reviewCount,
      },
      create: {
        id: c.id,
        slug: c.slug,
        title: c.title,
        subtitle: c.subtitle,
        description: c.description,
        longDesc: c.longDesc,
        priceUsdt: c.priceUsdt,
        image: c.image,
        category: c.category,
        tags: c.tags,
        instructor: c.instructor,
        duration: c.duration,
        lessons: c.lessons,
        level: c.level,
        featured: c.featured,
        rating: c.rating,
        reviewCount: c.reviewCount,
      },
    });
    console.log(` ✅ ${upserted.slug} [₮${upserted.priceUsdt}]`);
  }

  const count = await prisma.course.count();
  console.log(`\n🎉 Successfully seeded ${count} courses in NeonDB!`);
}

seed()
  .catch((e) => {
    console.error("❌ Seed failed:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
